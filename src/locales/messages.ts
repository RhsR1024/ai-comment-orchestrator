function apply_params(template: string, params?: Record<string, string | number>): string {
  if (!params) {
    return template;
  }
  return Object.entries(params).reduce((message, [name, value]) => {
    return message.replaceAll(`{${name}}`, String(value));
  }, template);
}

export function resolve_message(
  key: string,
  params?: Record<string, string | number>
): string {
  return apply_params(MESSAGES_ZH[key] ?? key, params);
}

export function use_messages() {
  return {
    t: resolve_message
  };
}
